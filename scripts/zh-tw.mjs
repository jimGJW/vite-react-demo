const CHAR = new Map()
for (let i = 0; i < PAIRS.length; i += 2) {
  const s = PAIRS[i]
  const t = PAIRS[i + 1]
  if (s.length !== t.length) {
    throw new Error(`zh-tw 字表第 ${i / 2 + 1} 段长度不等：简 ${s.length} / 繁 ${t.length}`)
  }
  for (let j = 0; j < s.length; j++) CHAR.set(s[j], t[j])
}

