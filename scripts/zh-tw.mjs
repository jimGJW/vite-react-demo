export const SIMPLIFIED_CHARS = new Set([...CHAR].filter(([s, t]) => s !== t).map(([s]) => s))

/** 短词优先会造成误伤，按长度降序排列保证长词先命中 */
const LEX_SORTED = [...LEX].sort((a, b) => b[0].length - a[0].length)

/**
 * 简体文本转台湾繁体。对已是繁体的文本恒等（繁体字不在字表 key 内），可安全重复调用。
 */
export function toTraditional(text) {
  let out = text
  for (const [s, t] of LEX_SORTED) out = out.split(s).join(t)
  let chars = ''
  for (const ch of out) chars += CHAR.get(ch) ?? ch
  return chars
}

