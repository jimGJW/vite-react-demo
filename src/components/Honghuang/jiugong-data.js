/* =====================================================================
   九宫八卦阵
   ---------------------------------------------------------------------
   分层诚实原则（与星斗／神煞两阵同一套规矩，勿删）：
   - 骨架（可核）：洛书九宫数本身是一个三阶幻方 —— 横、竖、斜各十五，
     这是数学事实，可机器校验（见 tests/unit/jiugong.test.mjs）。
     卦位与八节出自《周易·说卦》两章原文。
   - 通行（待核）：八风名目见《淮南子·天文训》《白虎通·八风》一系，
     各家配位偶有出入；八门（开休生伤杜景死惊）属奇门遁甲，今本多为
     明清整理，先秦无「门」配「宫」的成文记载。
   - 演绎（小说）：把九宫八卦当「军阵」是演义与兵家传统
     （《三国志》只说诸葛亮「作八阵图」，未载阵形细节）；
     「九宫八卦阵」作为洪荒小说里的大阵名号，无《封神演义》逐字原文。

   盘面朝向：与周天盘同向 —— 北在上、东在左。传统洛书图与后天八卦图
   习惯「南上北下」（圣人南面而听天下），故本盘相当于把古图整体旋转
   180°；幻方性质与卦位相对关系完全不变，这一点在页面上明写。
   ===================================================================== */

