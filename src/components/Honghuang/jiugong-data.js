/**
 * 幻方的八条线（3 行 + 3 列 + 2 对角），由 GRID 现算，不手写：
 * 手写容易把「戴九履一」的古图朝向与本盘朝向弄混。
 */
export const LINES = (() => {
  const nums = GRID.flat()
  const at = (r, c) => GRID[r][c]
  const mk = (cells) => {
    const sum = cells.reduce((s, n) => s + at(n.r, n.c), 0)
    return { cells, sum }
  }
  const toCell = (n) => ({ ...POS[n], num: n })
  const rows = GRID.map((row) => mk(row.map(toCell)))
  const cols = [0, 1, 2].map((c) => mk(nums.filter((_, i) => i % 3 === c).map(toCell)))
  const diagA = mk([[0, 0], [1, 1], [2, 2]].map(([r, c]) => ({ r, c, num: at(r, c) })))
  const diagB = mk([[0, 2], [1, 1], [2, 0]].map(([r, c]) => ({ r, c, num: at(r, c) })))
  return [...rows, ...cols, diagA, diagB]
})()

