/**
 * 等距圆柱投影（Plate Carrée）。
 *
 * 单独成文件有两个原因：
 *  1. react-refresh 规则不允许组件文件里混导出函数（会破坏热更新边界）；
 *  2. 投影函数是纯计算，页面和组件都可能复用，不该依附于某个组件文件。
 *
 * 为什么用等距圆柱而不是墨卡托：墨卡托会让高纬地区横向拉伸到无穷，
 * 而轨道地面轨迹经常飞到 ±81°，那会把图拉得没法看。等距圆柱的经纬度是线性的，
 * 代价是面积失真——但这个页面的重点是「在地球哪一侧」，不是面积比较。
 */

export const MAP_W = 1000
export const MAP_H = 500

/** 经纬度 → SVG 坐标 */
export function project(lat, lon) {
  return {
    x: ((lon + 180) / 360) * MAP_W,
    // 纬度翻转：+90° 在顶部
    y: ((90 - lat) / 180) * MAP_H,
  }
}

