/** 把经纬度多边形数组转成 SVG path（一次算好缓存起来） */
let cachedLandPath = null
export function landPath() {
  if (cachedLandPath) return cachedLandPath
  const parts = LANDMASSES.map((poly) => {
    const d = poly
      .map(([lon, lat], i) => {
        const p = project(lat, lon)
        return `${i === 0 ? 'M' : 'L'}${p.x.toFixed(1)},${p.y.toFixed(1)}`
      })
      .join(' ')
    return `${d} Z`
  })
  cachedLandPath = parts.join(' ')
  return cachedLandPath
}

/**
 * 晨昏线。
 *
 * 做法：以太阳直射点方向 S 为法线，构造与之垂直的大圆（正午圈/午夜圈交界），
 * 沿该圆取 180 个点连成折线；夜半球则是「从夜面起点铺到图底」的封闭多边形。
 * 注意：这里算的是 ECI 系（惯性系）里的太阳方向，satellite.js 的 sunPos
 * 正是这个定义，所以不需要再减自转。
 */
export function terminatorPaths(subsolar) {
  if (!subsolar) return { line: '', shade: '' }
  const s = (subsolar.lat * Math.PI) / 180
  const l = (subsolar.lon * Math.PI) / 180
  const sx = Math.cos(s) * Math.cos(l)
  const sy = Math.cos(s) * Math.sin(l)
  const sz = Math.sin(s)

  // 构造与 S 垂直的两个正交单位向量
  let ux = -sy, uy = sx, uz = 0
  const un = Math.hypot(ux, uy, uz) || 1
  ux /= un; uy /= un; uz /= un
  const vx = sy * uz - sz * uy
  const vy = sz * ux - sx * uz
  const vz = sx * uy - sy * ux

  const pts = []
  for (let i = 0; i <= 180; i++) {
    const th = (i / 180) * Math.PI * 2
    const c = Math.cos(th), sn = Math.sin(th)
    const x = ux * c + vx * sn
    const y = uy * c + vy * sn
    const z = uz * c + vz * sn
    const r = Math.hypot(x, y, z)
    const lat = (Math.asin(z / r) * 180) / Math.PI
    const lon = (Math.atan2(y, x) * 180) / Math.PI
    pts.push(project(lat, lon))
  }

  const line = `${pts.map((p, i) => `${i === 0 ? 'M' : 'L'}${p.x.toFixed(1)},${p.y.toFixed(1)}`).join(' ')} Z`
  const anti = project(-subsolar.lat, subsolar.lon + 180)
  const shade = `${line} L${anti.x.toFixed(1)},${MAP_H} L0,${MAP_H} Z`
  return { line, shade }
}
